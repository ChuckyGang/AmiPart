#!/usr/bin/env python3
"""Generate host/gui_font.h from the X11 misc-fixed 8x13 ISO8859-1 font.

The misc-fixed fonts are in the public domain.  The generated header is
committed, so this script (and the font package) is only needed to
regenerate it:  python3 support/mkguifont.py [font.pcf.gz] > host/gui_font.h
"""
import gzip, io, sys
from PIL import PcfFontFile

src = sys.argv[1] if len(sys.argv) > 1 else \
    "/usr/share/fonts/X11/misc/8x13-ISO8859-1.pcf.gz"
f = PcfFontFile.PcfFontFile(io.BytesIO(gzip.open(src).read()), "iso8859-1")
W, H, ASC = 8, 13, 11
rows = []
for ch in range(256):
    g = f.glyph[ch]
    bits = [0] * H
    if g:
        (dx, dy), (x0, y0, x1, y1), src_box, im = g
        im = im.convert("1")
        for y in range(im.size[1]):
            for x in range(im.size[0]):
                px, py = x0 + x, ASC + y0 + y
                if im.getpixel((x, y)) and 0 <= px < W and 0 <= py < H:
                    bits[py] |= 0x80 >> px
    rows.append(bits)
print("/* Generated by support/mkguifont.py from X11 misc-fixed 8x13")
print("   (ISO8859-1, public domain).  Do not edit. */")
print("#define GUI_FONT_W %d\n#define GUI_FONT_H %d\n#define GUI_FONT_BASE %d" % (W, H, ASC))
print("static const unsigned char gui_font[256][%d] = {" % H)
for ch, bits in enumerate(rows):
    print("  {" + ",".join("0x%02x" % b for b in bits) + "}, /* %02x */" % ch)
print("};")
