#!/usr/bin/env python3
"""bin2c.py <input> <output.c> <symbol> - embed a binary file as a C array."""
import sys

src, dst, sym = sys.argv[1:4]
data = open(src, "rb").read()
with open(dst, "w") as f:
    f.write("/* GENERATED by support/bin2c.py from %s - do not edit. */\n" % src)
    f.write('#include <exec/types.h>\n#include "%s.h"\n\n' % sym)
    f.write("const ULONG %s_size = %dUL;\n" % (sym, len(data)))
    f.write("const UBYTE %s[%d] = {\n" % (sym, len(data)))
    for i in range(0, len(data), 16):
        f.write("    " + ",".join("0x%02X" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
